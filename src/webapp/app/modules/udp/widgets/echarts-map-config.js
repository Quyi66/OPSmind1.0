        function registerMap(mapType) {
            var d = $q.defer();
            $.get('app/modules/udp/assets/map-json/' + mapType + '.json')
                .done(function (geoJson) {
                    echarts.registerMap(mapType, geoJson);
                    d.resolve();
                }).fail(function () {
                d.reject(new Error('无法加载地图数据文件' + mapType));
            });
            return d.promise;
        }

