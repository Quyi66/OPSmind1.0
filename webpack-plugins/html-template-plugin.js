const fs = require('fs');
const path = require('path');

class HtmlTemplatePlugin {
    constructor(options = {}) {
        this.options = {
            modulesRoot: 'src/webapp/app/modules/',
            outputDir: 'tmp',
            ...options
        };
    }

    apply(compiler) {
        compiler.hooks.beforeCompile.tapAsync('HtmlTemplatePlugin', (params, callback) => {
            console.log('🔄 Compiling HTML templates...');
            
            try {
                this.compileTemplates();
                console.log('✅ HTML templates compiled successfully');
                callback();
            } catch (error) {
                console.error('❌ HTML template compilation failed:', error);
                callback(error);
            }
        });
    }

    compileTemplates() {
        const modulesRoot = this.options.modulesRoot;
        const outputDir = this.options.outputDir;

        // 确保输出目录存在
        if (!fs.existsSync(outputDir)) {
            fs.mkdirSync(outputDir, { recursive: true });
        }

        // 获取所有模块
        const modules = fs.readdirSync(modulesRoot)
            .filter(file => fs.statSync(path.join(modulesRoot, file)).isDirectory())
            .filter(name => name !== 'node_modules');

        modules.forEach(module => {
            const moduleDir = path.join(modulesRoot, module);
            const htmlFiles = this.getHtmlFiles(moduleDir);
            
            if (htmlFiles.length > 0) {
                const jsContent = this.generateTemplateJs(module, htmlFiles);
                const outputFile = path.join(outputDir, `oplus-${module}-tpls.js`);
                fs.writeFileSync(outputFile, jsContent);
                console.log(`......module [${module}]: ${htmlFiles.length} templates ==> oplus-${module}-tpls.js`);
            }
        });
    }

    getHtmlFiles(dir) {
        const files = [];
        
        const scanDir = (currentDir) => {
            const items = fs.readdirSync(currentDir);
            
            items.forEach(item => {
                const fullPath = path.join(currentDir, item);
                const stat = fs.statSync(fullPath);
                
                if (stat.isDirectory() && item !== 'node_modules') {
                    scanDir(fullPath);
                } else if (stat.isFile() && item.endsWith('.html')) {
                    files.push(fullPath);
                }
            });
        };

        scanDir(dir);
        return files.sort(); // 确保文件顺序一致
    }

    generateTemplateJs(moduleName, htmlFiles) {
        const templates = htmlFiles.map(filePath => {
            const content = fs.readFileSync(filePath, 'utf8');
            const relativePath = path.relative('src/webapp', filePath).replace(/\\/g, '/');
            
            // 转义 HTML 内容
            const escapedContent = content
                .replace(/\\/g, '\\\\')
                .replace(/'/g, "\\'")
                .replace(/\r?\n/g, '\\n')
                .replace(/\t/g, '\\t');

            return `  $templateCache.put('${relativePath}', '${escapedContent}');`;
        });

        return `// This file is generated automatically by webpack
// DO NOT EDIT THIS FILE!
// Edit HTML template files instead.

angular.module('oplus.${moduleName}').run(['$templateCache', function($templateCache) {
${templates.join('\n')}
}]);
`;
    }
}

module.exports = HtmlTemplatePlugin;