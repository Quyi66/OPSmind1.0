        /**
         *
         * @param type
         * @returns {object<[number,number]>} Key is location name,
         * value is 2-D coordinates
         */
        function getGeoCoordMap(type) {
            if (type === 'world') {
                return WORLD_COUNTRY_CAPITAL_COORDS;
            } else if (type === 'china') {
                return CHINA_CITY_COORDS;
            }
            return {};
        }

        /**
         *
         * @param mapType
         * @param {string} nameFormat The format of location name, like full or simple
         * @returns {{name_in_map_json:string}} Mapping of name in map json and name used in data
         */
        function getNameMap(mapType, nameFormat) {
            var result = {};
            if (mapType === 'world') {
                return WORLD_COUNTRY_NAMEMAP;
            } else if (mapType === 'china') {
                // Districts of China
                if (nameFormat) {
                    Object.keys(CHINA_DISTRICT_NAMEMAP).forEach(function (key) {
                        result[key] = CHINA_DISTRICT_NAMEMAP[key][nameFormat];
                    });
                }
            } else {
                // Cities in a province/district
                if (nameFormat) {
                    var province = CHINA_CITIES_BY_DISTRICT[mapType];
                    if (province) {
                        Object.keys(province).forEach(function (city) {
                            result[city] = province[city][nameFormat] || city;
                        });
                    }
                }
            }
            return result;
        }
