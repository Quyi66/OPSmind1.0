const fs = require('fs');
const path = require('path');

class I18nCombinePlugin {
    constructor(options = {}) {
        this.options = {
            inputDir: options.inputDir || 'src/webapp/i18n',
            outputDir: options.outputDir || 'dist/webapp',
            outputFileName: options.outputFileName || 'app/modules/oplus-lang.js',
            ...options
        };
    }

    apply(compiler) {
        compiler.hooks.emit.tapAsync('I18nCombinePlugin', (compilation, callback) => {
            try {
                console.log('🌐 Combining i18n files...');
                
                const i18nDir = this.options.inputDir;
                const allLangs = {};

                // 读取所有语言目录
                if (fs.existsSync(i18nDir)) {
                    fs.readdirSync(i18nDir).forEach(file => {
                        const filePath = path.join(i18nDir, file);
                        if (fs.statSync(filePath).isDirectory()) {
                            const langKey = path.basename(file);
                            allLangs[langKey] = {};
                            
                            // 读取该语言目录下的所有 JSON 文件
                            fs.readdirSync(filePath)
                                .filter(f => f.endsWith('.json'))
                                .forEach(jsonFile => {
                                    try {
                                        const jsonPath = path.join(filePath, jsonFile);
                                        const content = fs.readFileSync(jsonPath, 'utf8');
                                        const jsonData = JSON.parse(content);
                                        Object.assign(allLangs[langKey], jsonData);
                                    } catch (error) {
                                        console.warn(`⚠️ Failed to parse ${jsonFile}:`, error.message);
                                    }
                                });
                        }
                    });
                }

                // 生成合并的 JS 文件内容
                const content = [
                    '// This file is generated by webpack i18n plugin.',
                    '// DO NOT EDIT THIS FILE !',
                    '// Edit i18n JSON files instead.',
                    '',
                    ';(function() {',
                    `  window["@oplus/langs"]=${JSON.stringify(allLangs, null, 2)};`,
                    '})();'
                ].join('\n');

                // 添加到 webpack 编译输出
                const outputPath = this.options.outputFileName;
                compilation.assets[outputPath] = {
                    source: () => content,
                    size: () => content.length
                };

                console.log(`✅ I18n files combined: ${Object.keys(allLangs).length} languages`);
                callback();
            } catch (error) {
                console.error('❌ I18n combine failed:', error);
                callback(error);
            }
        });
    }
}

module.exports = I18nCombinePlugin; 